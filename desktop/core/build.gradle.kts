plugins {
    alias(libs.plugins.kotlin.jvm)
}

// The product version lives in gradle/libs.versions.toml and reaches Kotlin as
// a generated constant, so `--version` can never disagree with the catalog.
val buildInfoDir = layout.buildDirectory.dir("generated/build-info")
val generateBuildInfo = tasks.register("generateBuildInfo") {
    val productVersion = version.toString()
    inputs.property("version", productVersion)
    outputs.dir(buildInfoDir)
    doLast {
        val file = buildInfoDir.get()
            .file("com/abrah/nightmare/desktop/core/BuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by :core:generateBuildInfo from gradle/libs.versions.toml.
            |// Do not edit; change the catalog instead.
            |package com.abrah.nightmare.desktop.core
            |
            |internal object BuildInfo {
            |    const val VERSION: String = "$productVersion"
            |}
            |""".trimMargin(),
        )
    }
}

kotlin {
    jvmToolchain(17)
    sourceSets["main"].kotlin.srcDir(generateBuildInfo)
}

dependencies {
    testImplementation(libs.junit)
}

tasks.test {
    useJUnit()
    testLogging { events("passed", "failed", "skipped") }
}
